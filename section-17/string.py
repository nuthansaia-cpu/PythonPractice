# String Representation
s1='Hello'
print(s1[0])
print(s1[-1])

print('--------------------------------------------------------------------')

# String Length
s1='Hello'
print(len(s1))

print('--------------------------------------------------------------------')

# Traversing a String
s1='Hello'
for x in s1:
	print(x)
print('--------------------------------------------------------------------')

# Another Example for Traversing String
for i in range(len(s1)):
	print(s1[i])

print('--------------------------------------------------------------------')

#String Literals
s1='Hello'
s2="Hello"
s3='''Hello'''
s4="""Hello
	How are you?"""
s5="clark's"
s6='clark"s'
print(s1,s2,s3,s4,s5,s6,sep="\n")

print('--------------------------------------------------------------------')

