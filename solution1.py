"""Take a user's name and print a welcome message.

Learning points:
1. input() always returns text (string).
2. f-strings are the cleanest way to build output messages.
"""

# Read a line of text from the user.
name = input("Enter your name: ")

# Use an f-string for clear and readable formatting.
print(f"Hello, {name}! Welcome to the program.")
print("I am learning GitHub.")
