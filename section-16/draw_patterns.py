for i in range(1,6):
	for j in range(1,6):
		if i>=j:
			print('*',end='')
	print('')

print('-----------------------------------------------------------------')

for i in range(1,6):
	for j in range(1,i+1):
		print('*',end='')
	print('')

print('-----------------------------------------------------------------')

for i in range(1,6):
	print('*' * i)

print('-----------------------------------------------------------------')

for i in range (1,6):
	for j in range(1,6-(i-1)):
		print('*',end='')
	print('')

